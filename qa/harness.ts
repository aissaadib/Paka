/* ------------------------------------------------------------------ parity */

function runParity(): any[] {
  const results: any[] = [];
  for (const scenario of scenarios()) {
    const before = renderWith(PreR1Renderer, scenario);
    const after = renderWith(HeadRenderer, scenario);
    results.push({
      name: scenario.name,
      rasterScale: scenario.rasterScale ?? 1,
      inkedPixels: inkedPixels(after.display, scenario.width, scenario.height),
      display: comparePixels(before.display, after.display, scenario.width, scenario.height, 2),
      export: comparePixels(before.exported, after.exported, scenario.width, scenario.height, 2),
    });
  }
  return results;
}

/* --------------------------------------------------- live/commit/rebuild */

function runInvariants(): any[] {
  const results: any[] = [];
  for (const scenario of scenarios()) {
    const elements = scenario.layers[0].elements ?? [];
    let liveIndex = -1;
    for (let index = elements.length - 1; index >= 0; index -= 1) {
      if (elements[index].kind === undefined) {
        liveIndex = index;
        break;
      }
    }
    if (liveIndex === -1) {
      results.push({ name: scenario.name, skipped: "no stroke element to draw live" });
      continue;
    }
    const priorElements = elements.slice(0, liveIndex);
    const doc = buildDoc(scenario);
    const layerId = doc.layers[0].id;
    // The rewritten elements (with the real layer id) are what the renderer
    // sees, so the live stroke has to be built from those.
    const resolved = currentSource.get(layerId) ?? [];
    const liveStroke = { ...resolved[liveIndex], id: nextId("live") };
    const canvas = document.createElement("canvas");
    const renderer = new HeadRenderer({
      canvas,
      strokeSource,
      rasterScale: scenario.rasterScale ?? 1,
    });
    renderer.setDocument(doc);
    renderer.setViewport({ zoom: 1, offsetX: 0, offsetY: 0 });
    renderer.setDisplaySize(scenario.width, scenario.height, 1);
    renderer.render();

    currentSource.set(layerId, priorElements);
    renderer.invalidateLayer(layerId);
    renderer.render();
    renderer.beginStroke(liveStroke);
    renderer.extendStroke(liveStroke, 0);
    renderer.render();
    const live = readCanvas(canvas);

    renderer.endStroke(liveStroke);
    renderer.render();
    const committed = readCanvas(canvas);

    // A rebuild is what undo/redo and a reopened project do.
    currentSource.set(layerId, [...priorElements, liveStroke]);
    renderer.invalidateLayer(layerId);
    renderer.render();
    const rebuilt = readCanvas(canvas);

    const exported = readCanvas(renderer.composeDocumentImage());

    results.push({
      name: scenario.name,
      inkedPixels: inkedPixels(committed, scenario.width, scenario.height),
      liveVsCommitted: comparePixels(live, committed, scenario.width, scenario.height, 2),
      committedVsRebuilt: comparePixels(committed, rebuilt, scenario.width, scenario.height, 2),
      rebuiltVsExport: comparePixels(rebuilt, exported, scenario.width, scenario.height, 2),
    });
  }
  return results;
}

/* --------------------------------------------------------------- area + time */

function buildAreaScenario(count: number, size: number, dense: boolean): Scenario {
  const elements: any[] = [];
  for (let index = 0; index < count; index += 1) {
    if (dense) {
      const xs: number[] = [];
      const ys: number[] = [];
      for (let step = 0; step < 60; step += 1) {
        xs.push((step / 59) * (size - 4) + 2);
        ys.push(2 + ((step % 2) * (size - 4)));
      }
      elements.push(stroke("L0", xs, ys, { size: 6 }));
    } else {
      const x = 10 + (index % 20) * 8;
      const y = 10 + Math.floor(index / 20) * 8;
      elements.push(stroke("L0", [x, x + 3], [y, y + 3], { size: 6 }));
    }
  }
  return { name: "area", width: size, height: size, layers: [{ elements }] };
}

/**
 * The area a rebuild touches.
 *
 * The counters are reset after the first build, so only the rebuild is
 * measured: the layer's own single full clear, the per-element clears of the
 * stroke buffer and the per-element blends onto the layer surface.
 */
function measureArea(Renderer: Any, scenario: Scenario, rasterScale: number): any {
  const instrument = installAreaInstrument();
  try {
    const doc = buildDoc(scenario);
    const canvas = document.createElement("canvas");
    const renderer = new Renderer({ canvas, strokeSource, rasterScale });
    renderer.setDocument(doc);
    renderer.setViewport({ zoom: 1, offsetX: 0, offsetY: 0 });
    renderer.setDisplaySize(scenario.width, scenario.height, 1);
    renderer.render();
    instrument.reset();
    renderer.invalidateLayer(doc.layers[0].id);
    renderer.render();
    const canvases = instrument.canvases;
    const buffer = instrument.stats(canvases[1]);
    const surface = instrument.stats(canvases[2]);
    return {
      bufferClearCalls: buffer.clearCalls,
      bufferClearArea: buffer.clearArea,
      surfaceDrawCalls: surface.drawCalls,
      surfaceDrawArea: surface.drawArea,
      surfaceClearArea: surface.clearArea,
      totalTouched: buffer.clearArea + surface.drawArea + surface.clearArea,
    };
  } finally {
    instrument.restore();
  }
}

function measureTime(Renderer: Any, scenario: Scenario, rasterScale: number, rounds: number): number[] {
  const doc = buildDoc(scenario);
  const canvas = document.createElement("canvas");
  const renderer = new Renderer({ canvas, strokeSource, rasterScale });
  renderer.setDocument(doc);
  renderer.setViewport({ zoom: 1, offsetX: 0, offsetY: 0 });
  renderer.setDisplaySize(scenario.width, scenario.height, 1);
  renderer.render();
  const layerId = doc.layers[0].id;
  const context = canvas.getContext("2d");
  const samples: number[] = [];
  for (let round = 0; round < rounds; round += 1) {
    renderer.invalidateLayer(layerId);
    const start = performance.now();
    renderer.render();
    context.getImageData(0, 0, 1, 1);
    samples.push(performance.now() - start);
  }
  return samples;
}

function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 0) {
    return (sorted[middle - 1] + sorted[middle]) / 2;
  }
  return sorted[middle];
}

function runCost(): any[] {
  const results: any[] = [];
  const cases = [
    { name: "1024x1024-s1-25-short", size: 1024, count: 25, dense: false, scale: 1 },
    { name: "1024x1024-s1-100-short", size: 1024, count: 100, dense: false, scale: 1 },
    { name: "1024x1024-s2-100-short", size: 1024, count: 100, dense: false, scale: 2 },
    { name: "2048x2048-s2-25-short", size: 2048, count: 25, dense: false, scale: 2 },
    { name: "2048x2048-s2-100-short", size: 2048, count: 100, dense: false, scale: 2 },
    { name: "2048x2048-s2-25-dense", size: 2048, count: 25, dense: true, scale: 2 },
  ];
  for (const testCase of cases) {
    const scenario = buildAreaScenario(testCase.count, testCase.size, testCase.dense);
    const before = measureArea(PreR1Renderer, scenario, testCase.scale);
    const after = measureArea(HeadRenderer, scenario, testCase.scale);
    const beforeTimes: number[] = [];
    const afterTimes: number[] = [];
    for (let round = 0; round < 3; round += 1) {
      beforeTimes.push(...measureTime(PreR1Renderer, scenario, testCase.scale, 1));
      afterTimes.push(...measureTime(HeadRenderer, scenario, testCase.scale, 1));
    }
    results.push({
      name: testCase.name,
      document: `${testCase.size}x${testCase.size}`,
      rasterScale: testCase.scale,
      elements: testCase.count,
      area: {
        before,
        after,
        areaFactor:
          after.totalTouched > 0 ? before.totalTouched / after.totalTouched : Number.POSITIVE_INFINITY,
      },
      timeMs: {
        before: median(beforeTimes),
        after: median(afterTimes),
        factor: median(afterTimes) > 0 ? median(beforeTimes) / median(afterTimes) : Number.POSITIVE_INFINITY,
        beforeSamples: beforeTimes,
        afterSamples: afterTimes,
      },
    });
  }
  return results;
}

