/**
 * QA harness for the bounded-rasterization change (R1, commit 4ac040b).
 *
 * It answers four questions with real Chromium Canvas 2D pixels:
 *
 *  1. PARITY - does the shipped renderer produce the same picture as the
 *     renderer as it was before R1 (commit 520aa77)? Compared over the WHOLE
 *     canvas, not a sample point.
 *  2. INVARIANT - inside the shipped renderer, do live drawing, the committed
 *     stroke, a rebuild (undo/redo path) and the PNG export agree?
 *  3. COVERAGE - every comparison reports how many pixels were actually inked,
 *     so a vacuous comparison (two empty documents) cannot pass silently.
 *  4. COST - how much area does a rebuild touch, and how long does it take,
 *     before and after R1?
 *
 * Nothing here changes production code: the "before" renderer is a copy in
 * qa/preR1/ and both are driven through their public API.
 */
import { Canvas2DRenderer as HeadRenderer } from "/src/core/rendering/Canvas2DRenderer";
import { Canvas2DRenderer as PreR1Renderer } from "/qa/preR1/Canvas2DRenderer";
import { createDocument, createLayer } from "/src/core/document/document";
import { DEFAULT_BRUSH } from "/src/core/brushes/defaults";

/* eslint-disable @typescript-eslint/no-explicit-any */
type Any = any;

/* ------------------------------------------------------------------ brushes */

const brush = (patch: Partial<typeof DEFAULT_BRUSH>): any => ({
  ...DEFAULT_BRUSH,
  color: "#101216",
  ...patch,
});

/* ---------------------------------------------------------------- elements */

let idCounter = 0;
const nextId = (prefix: string): string => `${prefix}-${(idCounter += 1)}`;

function stroke(
  layerId: string,
  xs: number[],
  ys: number[],
  patch: Partial<typeof DEFAULT_BRUSH> = {},
  extra: Record<string, unknown> = {},
): any {
  return {
    id: nextId("stroke"),
    layerId,
    brush: brush(patch),
    xs,
    ys,
    pressures: xs.map(() => 1),
    times: xs.map((_v, index) => index * 16),
    startTime: 0,
    ...extra,
  };
}

function fillPatch(layerId: string, x: number, y: number, width: number, height: number): any {
  const mask = new Uint8Array(width * height);
  for (let row = 0; row < height; row += 1) {
    for (let column = 0; column < width; column += 1) {
      mask[row * width + column] = 255;
    }
  }
  return {
    id: nextId("fill"),
    layerId,
    kind: "fill",
    color: "#2f6f4f",
    x,
    y,
    width,
    height,
    mask,
  };
}

function gradient(layerId: string, type: "linear" | "radial"): any {
  return {
    id: nextId("grad"),
    layerId,
    kind: "gradient",
    type,
    x1: 10,
    y1: 10,
    x2: 60,
    y2: 40,
    stops: [
      { offset: 0, color: "#ffffff" },
      { offset: 1, color: "#204080" },
    ],
    opacity: 1,
  };
}

/* ---------------------------------------------------------------- scenarios */

interface LayerSpec {
  elements: any[];
  opacity?: number;
  blendMode?: string;
  visible?: boolean;
}

interface Scenario {
  name: string;
  width: number;
  height: number;
  rasterScale?: number;
  layers: LayerSpec[];
}

/**
 * The elements the renderer can see.
 *
 * The renderer asks the source for the elements of a layer id; the layer ids
 * are generated by `createLayer`, so the source is a single module-level map
 * that `buildDoc` repopulates. (A per-render map would silently hand the
 * renderer an empty layer - the comparison would then be vacuous.)
 */
const currentSource = new Map<string, any[]>();

const strokeSource = {
  listStrokes: (layerId: string): any[] =>
    (currentSource.get(layerId) ?? []).filter((element) => element.kind === undefined),
  listElements: (layerId: string): any[] => currentSource.get(layerId) ?? [],
};

function buildDoc(scenario: Scenario): any {
  currentSource.clear();
  const doc = createDocument({ width: scenario.width, height: scenario.height });
  doc.layers.length = 0;
  scenario.layers.forEach((spec, index) => {
    const layer = createLayer(`Layer ${index + 1}`) as any;
    layer.visible = spec.visible !== false;
    layer.opacity = spec.opacity ?? 1;
    layer.blendMode = spec.blendMode ?? "normal";
    doc.layers.push(layer);
    // The scenarios name their layers "L0"/"L1"; the renderer resolves a
    // stroke's own layer id on the live and commit paths, so the elements have
    // to carry the real id - as the engine always does.
    const elements = spec.elements.map((element) => ({ ...element, layerId: layer.id }));
    currentSource.set(layer.id, elements);
  });
  doc.activeLayerId = doc.layers[0].id;
  return doc;
}

/* ----------------------------------------------------------------- reading */

function readCanvas(canvas: any): Uint8ClampedArray {
  const ctx = canvas.getContext("2d");
  return ctx.getImageData(0, 0, canvas.width, canvas.height).data;
}

/**
 * How many pixels differ from the paper.
 *
 * The paper is the document background; the border hairline is excluded. A
 * comparison that reports zero inked pixels is vacuous, so every comparison
 * carries this number.
 */
function inkedPixels(
  data: Uint8ClampedArray,
  width: number,
  height: number,
  paper: number[] = [255, 255, 255],
): number {
  let count = 0;
  for (let index = 0; index < data.length; index += 4) {
    const x = (index / 4) % width;
    const y = Math.floor(index / 4 / width);
    if (x < 2 || y < 2 || x >= width - 2 || y >= height - 2) {
      continue;
    }
    if (
      Math.abs(data[index] - paper[0]) > 2 ||
      Math.abs(data[index + 1] - paper[1]) > 2 ||
      Math.abs(data[index + 2] - paper[2]) > 2
    ) {
      count += 1;
    }
  }
  return count;
}

interface Diff {
  identical: boolean;
  width: number;
  height: number;
  pixelsCompared: number;
  pixelsDiffering: number;
  maxChannelDelta: number;
  firstDifference: { x: number; y: number; expected: number[]; actual: number[] } | null;
  differenceBounds: { left: number; top: number; right: number; bottom: number } | null;
}

function comparePixels(
  a: Uint8ClampedArray,
  b: Uint8ClampedArray,
  width: number,
  height: number,
  ignoreBorder = 0,
): Diff {
  const result: Diff = {
    identical: a.length === b.length && a.length > 0,
    width,
    height,
    pixelsCompared: a.length / 4,
    pixelsDiffering: 0,
    maxChannelDelta: 0,
    firstDifference: null,
    differenceBounds: null,
  };
  if (a.length !== b.length) {
    result.identical = false;
    return result;
  }
  let left = Number.POSITIVE_INFINITY;
  let top = Number.POSITIVE_INFINITY;
  let right = Number.NEGATIVE_INFINITY;
  let bottom = Number.NEGATIVE_INFINITY;
  for (let index = 0; index < a.length; index += 4) {
    const pixel = index / 4;
    const x = pixel % width;
    const y = Math.floor(pixel / width);
    if (
      ignoreBorder > 0 &&
      (x < ignoreBorder ||
        y < ignoreBorder ||
        x >= width - ignoreBorder ||
        y >= height - ignoreBorder)
    ) {
      continue;
    }
    let differs = false;
    let delta = 0;
    for (let channel = 0; channel < 4; channel += 1) {
      const difference = Math.abs(a[index + channel] - b[index + channel]);
      if (difference > 0) {
        differs = true;
      }
      if (difference > delta) {
        delta = difference;
      }
    }
    if (!differs) {
      continue;
    }
    result.pixelsDiffering += 1;
    if (delta > result.maxChannelDelta) {
      result.maxChannelDelta = delta;
    }
    left = Math.min(left, x);
    top = Math.min(top, y);
    right = Math.max(right, x);
    bottom = Math.max(bottom, y);
    if (!result.firstDifference) {
      result.firstDifference = {
        x,
        y,
        expected: Array.from(a.slice(index, index + 4)),
        actual: Array.from(b.slice(index, index + 4)),
      };
    }
  }
  result.identical = result.pixelsDiffering === 0;
  if (result.pixelsDiffering > 0) {
    result.differenceBounds = { left, top, right, bottom };
  }
  return result;
}

/* -------------------------------------------------------------- instrument */

/**
 * Wraps the 2D context of every canvas so the area each call touches can be
 * measured: the destination rectangle times the determinant of the transform
 * that was live when the call was made.
 */
interface AreaStats {
  clearCalls: number;
  clearArea: number;
  drawCalls: number;
  drawArea: number;
}

interface Instrument {
  restore: () => void;
  stats: (canvas: any) => AreaStats;
  reset: () => void;
  canvases: any[];
}

function installAreaInstrument(): Instrument {
  const stats = new Map<any, AreaStats>();
  const order: any[] = [];
  const originalGetContext = HTMLCanvasElement.prototype.getContext;

  const multiply = (m: number[], n: number[]): number[] => [
    m[0] * n[0] + m[2] * n[1],
    m[1] * n[0] + m[3] * n[1],
    m[0] * n[2] + m[2] * n[3],
    m[1] * n[2] + m[3] * n[3],
    m[0] * n[4] + m[2] * n[5] + m[4],
    m[1] * n[4] + m[3] * n[5] + m[5],
  ];

  HTMLCanvasElement.prototype.getContext = function patched(
    this: any,
    type: string,
    ...rest: any[]
  ): any {
    const context = originalGetContext.call(this, type, ...rest);
    if (type !== "2d" || !context || (context as any).__qaInstrumented) {
      return context;
    }
    (context as any).__qaInstrumented = true;
    if (!stats.has(this)) {
      stats.set(this, { clearCalls: 0, clearArea: 0, drawCalls: 0, drawArea: 0 });
      order.push(this);
    }
    const entry = stats.get(this)!;
    let matrix: number[] = [1, 0, 0, 1, 0, 0];
    const stack: number[][] = [];
    const determinant = (): number => Math.abs(matrix[0] * matrix[3] - matrix[1] * matrix[2]);

    const originalSetTransform = context.setTransform.bind(context);
    context.setTransform = (a: number, b: number, c: number, d: number, e: number, f: number) => {
      matrix = [a, b, c, d, e, f];
      originalSetTransform(a, b, c, d, e, f);
    };
    const originalSave = context.save.bind(context);
    context.save = () => {
      stack.push(matrix.slice());
      originalSave();
    };
    const originalRestore = context.restore.bind(context);
    context.restore = () => {
      const previous = stack.pop();
      if (previous) {
        matrix = previous;
      }
      originalRestore();
    };
    const originalTransform = context.transform.bind(context);
    context.transform = (a: number, b: number, c: number, d: number, e: number, f: number) => {
      matrix = multiply(matrix, [a, b, c, d, e, f]);
      originalTransform(a, b, c, d, e, f);
    };
    const originalClearRect = context.clearRect.bind(context);
    context.clearRect = (x: number, y: number, width: number, height: number) => {
      entry.clearCalls += 1;
      entry.clearArea += Math.abs(width * height * determinant());
      originalClearRect(x, y, width, height);
    };
    const originalDrawImage = context.drawImage.bind(context);
    context.drawImage = (...args: any[]) => {
      const width = args.length === 5 ? args[3] : args[7];
      const height = args.length === 5 ? args[4] : args[8];
      entry.drawCalls += 1;
      entry.drawArea += Math.abs(width * height * determinant());
      originalDrawImage(...args);
    };
    return context;
  };

  return {
    restore: () => {
      HTMLCanvasElement.prototype.getContext = originalGetContext;
    },
    stats: (canvas: any) =>
      stats.get(canvas) ?? { clearCalls: 0, clearArea: 0, drawCalls: 0, drawArea: 0 },
    reset: () => {
      for (const entry of stats.values()) {
        entry.clearCalls = 0;
        entry.clearArea = 0;
        entry.drawCalls = 0;
        entry.drawArea = 0;
      }
    },
    canvases: order,
  };
}

/* --------------------------------------------------------------- rendering */

function renderWith(
  Renderer: Any,
  scenario: Scenario,
  options: { rasterScale?: number } = {},
): { display: Uint8ClampedArray; exported: Uint8ClampedArray; canvas: any; renderer: Any } {
  const doc = buildDoc(scenario);
  const canvas = document.createElement("canvas");
  const renderer = new Renderer({
    canvas,
    strokeSource,
    rasterScale: options.rasterScale ?? scenario.rasterScale ?? 1,
  });
  renderer.setDocument(doc);
  renderer.setViewport({ zoom: 1, offsetX: 0, offsetY: 0 });
  renderer.setDisplaySize(scenario.width, scenario.height, 1);
  renderer.render();
  const display = readCanvas(canvas);
  const exported = readCanvas(renderer.composeDocumentImage());
  return { display, exported, canvas, renderer };
}

