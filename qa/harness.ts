/**
 * Renders every scenario with the shipped renderer and with each mutant
 * (a renderer copy with one line changed) and compares the whole canvas.
 *
 * A mutant that changes pixels but passes the repository's test suite is a
 * gap in the regression tests.
 */
export async function runMutants(): Promise<any> {
  const mutants: Record<string, any> = {
    "m4-feather-spread": (await import("/qa/mutants/m4-feather-spread/Canvas2DRenderer.ts")).Canvas2DRenderer,
    "m6-floored-bounds": (await import("/qa/mutants/m6-floored-bounds/Canvas2DRenderer.ts")).Canvas2DRenderer,
  };
  const results: any[] = [];
  for (const scenario of scenarios()) {
    const shipped = renderWith(HeadRenderer, scenario);
    for (const [name, Renderer] of Object.entries(mutants)) {
      const mutant = renderWith(Renderer, scenario);
      results.push({
        scenario: scenario.name,
        mutant: name,
        inkedPixels: inkedPixels(shipped.display, scenario.width, scenario.height),
        display: comparePixels(shipped.display, mutant.display, scenario.width, scenario.height, 2),
        export: comparePixels(shipped.exported, mutant.exported, scenario.width, scenario.height, 2),
      });
    }
  }
  return results;
}

export async function runAll(): Promise<any> {
  const parity = runParity();
  const invariants = runInvariants();
  const cost = runCost();
  const parityFailures = parity.filter(
    (entry: any) => !entry.display.identical || !entry.export.identical || entry.inkedPixels === 0,
  );
  const invariantFailures = invariants.filter(
    (entry: any) =>
      entry.skipped === undefined &&
      (!entry.liveVsCommitted.identical ||
        !entry.committedVsRebuilt.identical ||
        !entry.rebuiltVsExport.identical),
  );
  return {
    generatedAt: new Date().toISOString(),
    userAgent: navigator.userAgent,
    parity,
    invariants,
    cost,
    summary: {
      parityScenarios: parity.length,
      parityFailures: parityFailures.map((entry: any) => entry.name),
      invariantScenarios: invariants.length,
      invariantFailures: invariantFailures.map((entry: any) => entry.name),
    },
  };
}

(window as any).__qa = { runAll, runParity, runInvariants, runCost, runMutants };
